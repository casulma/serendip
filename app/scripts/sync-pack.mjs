// Copies the content pack produced by content/ into the app, and generates
// the static image map Metro needs (it can only bundle literal require() paths).
// Runs before `expo start`, before typechecking, and on EAS after install.
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const APP = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(APP, "..", "content", "out");
const DEST = join(APP, "assets", "pack");

if (!existsSync(join(SRC, "pack.json"))) {
  console.error("content/out/pack.json introuvable : lancez d'abord `pnpm --filter @serendip/content all`.");
  process.exit(1);
}

rmSync(DEST, { recursive: true, force: true });
mkdirSync(join(DEST, "flags"), { recursive: true });
copyFileSync(join(SRC, "pack.json"), join(DEST, "pack.json"));

const flags = existsSync(join(SRC, "assets", "flags")) ? readdirSync(join(SRC, "assets", "flags")).sort() : [];
for (const f of flags) copyFileSync(join(SRC, "assets", "flags", f), join(DEST, "flags", f));

const lines = [
  "// Generated by scripts/sync-pack.mjs. Do not edit.",
  "export const IMAGES: Record<string, number> = {",
  ...flags.map((f) => `  "flags/${f}": require("../../assets/pack/flags/${f}"),`),
  "};",
  "",
];
mkdirSync(join(APP, "src", "pack"), { recursive: true });
writeFileSync(join(APP, "src", "pack", "images.generated.ts"), lines.join("\n"));
// The version alone, so that launches can skip loading the 6 MB pack when it is already imported.
const { version } = JSON.parse(readFileSync(join(SRC, "pack.json"), "utf8"));
writeFileSync(
  join(APP, "src", "pack", "version.generated.ts"),
  `// Generated by scripts/sync-pack.mjs. Do not edit.\nexport const PACK_VERSION = ${JSON.stringify(version)};\n`,
);
console.log(`[sync-pack] pack.json + ${flags.length} images copiés dans app/assets/pack`);
