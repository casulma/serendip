// Copies the question pack produced by content/ into the app, and writes its
// version alone so that launches can skip loading the pack when already imported.
// Runs before `expo start`, before typechecking, and on EAS after install.
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const APP = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(APP, "..", "content", "out", "pack.json");
const DEST = join(APP, "assets", "pack");

if (!existsSync(SRC)) {
  console.error("content/out/pack.json introuvable : lancez d'abord `pnpm --filter @serendip/content all`.");
  process.exit(1);
}

rmSync(DEST, { recursive: true, force: true });
mkdirSync(DEST, { recursive: true });
copyFileSync(SRC, join(DEST, "pack.json"));

const { version, questions } = JSON.parse(readFileSync(SRC, "utf8"));
mkdirSync(join(APP, "src", "pack"), { recursive: true });
writeFileSync(
  join(APP, "src", "pack", "version.generated.ts"),
  `// Generated by scripts/sync-pack.mjs. Do not edit.\nexport const PACK_VERSION = ${JSON.stringify(version)};\n`,
);
console.log(`[sync-pack] pack ${version} (${questions?.length ?? 0} questions) copié dans app/assets/pack`);
